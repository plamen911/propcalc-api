#!/usr/bin/env bash
#
# Prepares everything the test suite needs on a developer machine:
#
#   1. Test-only JWT keys in var/jwt/ (gitignored - never the production keys).
#   2. .env.test.local with a DSN pointing at a dedicated test database, derived
#      from your existing .env so no credentials are ever written into a committed
#      file. .env.test.local is gitignored.
#   3. The test database itself.
#
# Safe to re-run; nothing is overwritten unless you ask for it.

set -euo pipefail

cd "$(dirname "$0")/.."

TEST_DB_NAME="${TEST_DB_NAME:-propcalc_test}"

# --- 1. Test JWT keys -------------------------------------------------------
if [ ! -f var/jwt/private.pem ]; then
    echo "==> Generating throwaway JWT keys in var/jwt/"
    mkdir -p var/jwt
    openssl genpkey -out var/jwt/private.pem \
        -aes256 -pass pass:testpassphrase \
        -algorithm RSA -pkeyopt rsa_keygen_bits:4096 2>/dev/null
    openssl pkey -in var/jwt/private.pem -passin pass:testpassphrase \
        -out var/jwt/public.pem -pubout 2>/dev/null
    chmod 600 var/jwt/private.pem
else
    echo "==> var/jwt/private.pem already exists, keeping it"
fi

# --- 2. .env.test.local -----------------------------------------------------
if [ ! -f .env.test.local ]; then
    if [ -f .env ]; then
        echo "==> Writing .env.test.local (test DSN derived from .env, gitignored)"
        php -r '
            require "vendor/autoload.php";
            $dbName = $argv[1];
            $dotenv = new Symfony\Component\Dotenv\Dotenv();
            $vars = $dotenv->parse(file_get_contents(".env"), ".env");
            if (!isset($vars["DATABASE_URL"])) {
                fwrite(STDERR, "No DATABASE_URL in .env; edit .env.test.local by hand.\n");
                exit(1);
            }
            $parts = parse_url($vars["DATABASE_URL"]);
            $auth = $parts["user"] ?? "";
            if (isset($parts["pass"]) && $parts["pass"] !== "") {
                $auth .= ":" . $parts["pass"];
            }
            $dsn = sprintf(
                "%s://%s@%s%s/%s%s",
                $parts["scheme"] ?? "mysql",
                $auth,
                $parts["host"] ?? "127.0.0.1",
                isset($parts["port"]) ? ":" . $parts["port"] : "",
                $dbName,
                isset($parts["query"]) ? "?" . $parts["query"] : ""
            );
            file_put_contents(".env.test.local",
                "# Generated by bin/setup-test-db.sh. Gitignored - never commit this file.\n"
                . "DATABASE_URL=\"" . $dsn . "\"\n"
            );
        ' "$TEST_DB_NAME"
    else
        echo "!! No .env found. Create .env.test.local manually with a DATABASE_URL"
        echo "   pointing at a database whose name ends in _test."
    fi
else
    echo "==> .env.test.local already exists, keeping it"
fi

# --- 3. Test database -------------------------------------------------------
echo "==> Creating the test database if it does not exist"
php bin/console doctrine:database:create --if-not-exists --env=test --no-interaction

echo
echo "Done. Run the suite with:  composer test"
